"""Local file storage (PRD Ch3.9 — development storage backend).

Production swaps this for AWS S3 via configuration only (`AWS_S3_BUCKET`
etc. in core/config.py); callers depend only on `save_upload`'s signature,
never on the storage mechanism.
"""

import uuid
from pathlib import Path

from fastapi import UploadFile

from app.core.config import settings
from app.core.exceptions import AppError

DOCUMENT_CONTENT_TYPES = {
    "application/pdf": "pdf",
    "image/jpeg": "jpg",
    "image/png": "png",
}

# Recording formats produced by MediaRecorder across common browsers
# (Ch9.5/Ch17.2 — the consultation recording pipeline; STT processing of
# these files is implemented in the AI Engine milestone).
AUDIO_CONTENT_TYPES = {
    "audio/webm": "webm",
    "audio/ogg": "ogg",
    "audio/mp4": "m4a",
    "audio/mpeg": "mp3",
    "audio/wav": "wav",
    "audio/x-wav": "wav",
}


class DocumentUploadError(AppError):
    status_code = 422
    error_code = "DOCUMENT_UPLOAD_FAILED"


class AudioUploadError(AppError):
    status_code = 422
    error_code = "AUDIO_UPLOAD_FAILED"


async def _save(
    file: UploadFile,
    *,
    subdir: str,
    allowed_types: dict[str, str],
    error_cls: type[AppError],
    unsupported_message: str,
    max_mb: int,
) -> tuple[str, str, int]:
    content_type = file.content_type or ""
    if content_type not in allowed_types:
        raise error_cls(unsupported_message)

    extension = allowed_types[content_type]
    max_bytes = max_mb * 1024 * 1024

    contents = await file.read()
    if len(contents) > max_bytes:
        raise error_cls(f"File exceeds the {max_mb}MB upload limit.")
    if len(contents) == 0:
        raise error_cls("The uploaded file is empty.")

    directory = Path(settings.local_storage_dir) / subdir
    directory.mkdir(parents=True, exist_ok=True)

    filename = f"{uuid.uuid4()}.{extension}"
    file_path = directory / filename
    file_path.write_bytes(contents)

    relative_url = f"/{settings.local_storage_dir}/{subdir}/{filename}"
    return relative_url, extension, len(contents)


async def save_upload(file: UploadFile, *, subdir: str) -> tuple[str, str, int]:
    """Validates and persists a patient document. Returns (relative_url, extension, size_bytes)."""
    return await _save(
        file,
        subdir=subdir,
        allowed_types=DOCUMENT_CONTENT_TYPES,
        error_cls=DocumentUploadError,
        unsupported_message="Only PDF, JPG, and PNG files are supported.",
        max_mb=settings.max_upload_size_mb,
    )


async def save_audio_upload(file: UploadFile, *, subdir: str) -> tuple[str, str, int]:
    """Validates and persists a consultation recording. Returns (relative_url, extension, size_bytes)."""
    return await _save(
        file,
        subdir=subdir,
        allowed_types=AUDIO_CONTENT_TYPES,
        error_cls=AudioUploadError,
        unsupported_message="Unsupported audio format.",
        max_mb=settings.max_audio_upload_size_mb,
    )


def save_bytes(content: bytes, *, subdir: str, filename: str) -> str:
    """Persists server-generated bytes (e.g. a rendered PDF report) that
    never went through an `UploadFile`. Returns the relative_url in the
    same `/{local_storage_dir}/...` shape `_save()` produces, so it is
    interchangeable with uploaded-file URLs everywhere they're served from."""
    directory = Path(settings.local_storage_dir) / subdir
    directory.mkdir(parents=True, exist_ok=True)
    (directory / filename).write_bytes(content)
    return f"/{settings.local_storage_dir}/{subdir}/{filename}"
